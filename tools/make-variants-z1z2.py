#!/usr/bin/env python3
"""t2675u: build dialogue-variants.js from Eve-approved /workspace/dialogue-team/voice-variants-z1z2-joins.md (Part 1 only).
Lines are copied verbatim: [code, emotion, text]. v1 is never written here (it is the live text in the locked data files).
Zone 1 walls: {solo:{place,lines}, party:{place,lines}}. Zone 2 walls and joins: {place, lines}. Journal thoughts: "journal" (not spoken)."""
import re,json,sys
SRC=sys.argv[1] if len(sys.argv)>1 else '/workspace/dialogue-team/voice-variants-z1z2-joins.md'
OUT=sys.argv[2] if len(sys.argv)>2 else 'dialogue-variants.js'
md=open(SRC,encoding='utf-8').read()
part1=md.split('\n## Part 2')[0]
LINE=re.compile(r'^\d+\. `([A-Z])` \([^)]*\) \[(\w+)\] (.+)$')
PLACE=re.compile(r'`(PLACE: [^`]+)`')
JOUR=re.compile(r'^- \*\*JOURNAL THOUGHT \(note, not spoken\):\*\* (.+)$')
scenes={}
for sec in part1.split('\n#### ')[1:]:
  head,body=sec.split('\n',1);vid=head.split()[0];m=re.match(r'^(join-[a-z-]+|wall-z[12]-\d\d)-v(\d+)$',vid)
  if not m:raise SystemExit('bad id '+vid)
  scene,n=m.group(1),int(m.group(2))
  if n<2:raise SystemExit('v1 must not be in the variants file: '+vid)
  e={'id':vid};cur=None;forms={}
  for ln in body.split('\n'):
    s=ln.strip()
    if s.startswith('**Solo form:**'):cur='solo';forms[cur]={'place':PLACE.search(s).group(1),'lines':[]};continue
    if s.startswith('**Party form:**'):cur='party';forms[cur]={'place':PLACE.search(s).group(1),'lines':[]};continue
    if s.startswith('- `PLACE:'):e['place']=PLACE.search(s).group(1);continue
    j=JOUR.match(s)
    if j:e['journal']=j.group(1);continue
    l=LINE.match(s)
    if l:
      row=[l.group(1),l.group(2),l.group(3)]
      if cur:forms[cur]['lines'].append(row)
      else:e.setdefault('lines',[]).append(row)
  if forms:
    if set(forms)!={'solo','party'}:raise SystemExit('zone 1 wall needs solo and party forms: '+vid)
    e.update(forms);e['place']=forms['solo']['place']
  if not (e.get('lines') or forms):raise SystemExit('no lines '+vid)
  if 'place' not in e:raise SystemExit('no PLACE '+vid)
  scenes.setdefault(scene,[]).append(e)
# ---- Part 2: presence talks (AR add-ons). One stored pick per room ("ar1-01" -> ar1-01-v2 / -v3); the piece by suffix h/m/s/bs/br.
part2=md.split('\n## Part 2',1)[1] if '\n## Part 2' in md else ''
ar={};spoken2=0;notes2=0
for sec in part2.split('\n#### ')[1:]:
  head,body=sec.split('\n',1);vid=head.split()[0];m=re.match(r'^(ar[12]-0[1-4])-(h|m|s|bs|br)-v([23])$',vid)
  if not m:raise SystemExit('bad Part 2 id '+vid)
  room,suf,n=m.group(1),m.group(2),m.group(3)
  e={'id':vid,'lines':[]}
  for ln in body.split('\n'):
    s_=ln.strip()
    if s_.startswith('- `PLACE:'):e['place']=PLACE.search(s_).group(1);continue
    j=JOUR.match(s_)
    if j:e['journal']=j.group(1);notes2+=1;continue
    l=LINE.match(s_)
    if l:e['lines'].append([l.group(1),l.group(2),l.group(3)]);spoken2+=1
  if 'place' not in e:raise SystemExit('no PLACE '+vid)
  ver=room+'-v'+n;lst=ar.setdefault(room,{});ent=lst.setdefault(ver,{'id':ver,'pieces':{}})
  if suf in ent['pieces']:raise SystemExit('dup '+vid)
  ent['pieces'][suf]=e
for room in ar:ar[room]=[ar[room][k] for k in sorted(ar[room])]
npieces2=sum(len(v['pieces']) for r in ar.values() for v in r)
print('Part 2:',npieces2,'pieces,',spoken2,'spoken lines,',notes2,'journal notes')
order=["join-mira","join-sorrel","join-brunn-save","join-brunn-died","wall-z1-01","wall-z1-02","wall-z1-03","wall-z2-01","wall-z2-02","wall-z2-03","wall-z2-04"]
assert set(scenes)==set(order),sorted(scenes)
assert npieces2 in (0,70),npieces2
n=sum(len(v) for v in scenes.values())
for r in sorted(ar):scenes[r]=ar[r];order.append(r)
body=',\n'.join(' '+json.dumps(k)+':'+json.dumps(scenes[k],ensure_ascii=False) for k in order)
js=f'''/* DATA: dialogue variants (t2670u/t2675u). GENERATED by tools/make-variants-z1z2.py from Eve-approved
   /workspace/dialogue-team/voice-variants-z1z2-joins.md (Part 1: {n} variants, v2/v3; Part 2: {npieces2} presence-talk pieces,
   {spoken2} spoken lines, {notes2} journal notes). Lines verbatim. Do not hand-edit; re-run the tool.
   v1 = today's live text (story-data.js / package-pools-data.js), never listed here. Read by variety.js; see VARIANTS-MODULE.md.
   Shapes: joins and zone 2 walls {{id,place,lines,journal?}}; zone 1 walls {{id,place,solo:{{place,lines}},party:{{place,lines}},journal}};
   presence talks "ar<z>-<nn>": [{{id:"ar1-01-v2",pieces:{{h|m|s|bs|br:{{id,place,lines,journal?}}}}}}] (one pick per room, piece by suffix).
   lines: [[speaker,emotion,text]]; "journal" is a hero journal note (written at the next camp, never spoken). */
(function(root){{"use strict";
const scenes={{
{body}
}};
const API={{scenes,source:"voice-variants-z1z2-joins.md",count:{n},presencePieces:{npieces2}}};
if(typeof module!=="undefined"&&module.exports)module.exports=API;
root.DIALOGUE_VARIANTS=API;root.STORY_VARIANTS=API;
}})(typeof window!=="undefined"?window:globalThis);
'''
open(OUT,'w',encoding='utf-8').write(js);print('wrote',OUT,n,'variants',{k:len(v) for k,v in scenes.items()})
