"""Build t2103u-text.js from Eve-approved writing files (read-only sources in /workspace/dialogue-team/). Local only."""
import re,json,os
SRC='/workspace/dialogue-team/';ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def rd(n):return open(SRC+n,encoding='utf8').read()
def moods(txt):
  out={};pair=None
  for blk in re.split(r'\n(?=## |### )',txt):
    h=blk.split('\n',1)[0]
    if h.startswith('## ') and not h.startswith('## Specialist'):pair=h[3:].strip();out.setdefault(pair,[])
    elif h.startswith('### Line') and pair:
      g=lambda k:(re.search(r'- '+k+r'[^\n]*?:\s*(.*)',blk) or [None,''])[1].strip()
      m=re.search(r'- Speaker: (.+?) — "(.*)"',blk)
      out[pair].append({'who':m.group(1),'text':m.group(2),'face':g('Speaker face and body'),'listen':(re.search(r'- Listening \((.+?)\) face and body:\s*(.*)',blk).groups()),'backdrop':g('Backdrop')})
  return out
intro=moods(rd('mood-sheet-intro-sick-dad.md'))['Intro'];endings=moods(rd('mood-sheet-endings.md'))
def notes(txt,head):
  out={};cur=None;var=None
  for line in txt.split('\n'):
    if line.startswith('## ') and not line.startswith('## Specialist'):cur=line[3:].strip();var=None;continue
    if line.startswith('### Variant'):var=line.split()[2];continue
    m=re.match(head+r':\s*(.*)',line)
    if m and cur:
      key=cur+('#'+var if var else '');out[key]=[m.group(1)];last=key;continue
    if cur and line.strip() and not line.startswith(('Unlocks','When','---','#')) and 'last' in dir() and out.get(last) is not None and last.startswith(cur):out[last].append(line.strip())
    elif not line.strip() and cur:last=None
  return {k:'\n'.join(v) for k,v in out.items()}
wall=notes(rd('hero-wall-art-notes.md'),'Note');jour=notes(rd('journal-key-moments.md'),'Entry')
d={'intro':intro,'endings':endings,'wall':wall,'journal':jour}
open(os.path.join(ROOT,'t2103u-text.js'),'w',encoding='utf8').write('/* t2103u Eve-approved moods, wall-art edge notes and journal key moments (generated by tools/make-t2103u-text.py; do not hand-edit). */\n(function(r){const T='+json.dumps(d,ensure_ascii=False,indent=0)+';if(typeof module!=="undefined"&&module.exports)module.exports=T;else r.T2103U_TEXT=T;})(typeof window!=="undefined"?window:globalThis);\n')
print(len(intro),{k:len(v) for k,v in endings.items()},len(wall),len(jour))
