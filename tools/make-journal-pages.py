# Builds story-journal-pages.js from the live approved handwritten file (read-only source).
import re,json,sys
SRC='/workspace/dialogue-team/voice-t2194u-dialogue-journal.md'
def parse(src):
    out={};cur=None;var=None;buf=None
    def flush():
        if buf is not None:
            t='\n'.join(buf).strip('\n')
            if cur=='J-join-brunn': out.setdefault(cur,{})[var]=t
            else: out[cur]=t
    for line in open(src,encoding='utf8').read().split('\n'):
        m=re.match(r'^## (J-[a-z0-9-]+)\s*$',line); v=re.match(r'^### Variant ([AB])\b',line)
        if m or v or line.startswith('# '):
            flush();buf=None
            if m: cur=m.group(1);var=None
            if v: var=v.group(1)
            continue
        if line.strip()=='Journal:': buf=[];continue
        if buf is not None: buf.append(line)
    flush();return out
if __name__=='__main__':
    p=parse(SRC)
    js='/* t2194u approved handwritten camp pages (Eve-approved, generated by tools/make-journal-pages.py from voice-t2194u-dialogue-journal.md; do not hand-edit). Journal only, not spoken dialogue. */\n'
    js+='(function(root){"use strict";const P='+json.dumps(p,ensure_ascii=False,indent=0)+';\nroot.StoryJournalPages=Object.freeze({pages:P,source:{bytes:7709,lines:165}});if(typeof module!=="undefined")module.exports=root.StoryJournalPages;})(typeof window!=="undefined"?window:globalThis);\n'
    open('story-journal-pages.js','w',encoding='utf8').write(js)
    print(len(p),sum(len(v) if isinstance(v,dict) else 1 for v in p.values()))
